const rep = (text, from, to) => { if (!String(text).includes(from)) throw new Error('바꿀 문장을 못 찾음: ' + from.slice(0, 30)); return text.replace(from, to); };
const play = (m, label, fn) => { const item = m.playstyle.find(p => p.label === label); if (!item) throw new Error('playstyle 없음: ' + label); fn(item); };
const part = (m, id, from, to) => { const p = m.book.parts.find(x => x.id === id); p.summary = rep(p.summary, from, to); };

