module.exports = sid => ({
  source: __filename,
  changelog: [
    '## 2026-11-02 · 특성 ↔ 스킬 연결 도식',
    "- 스킬 구조 흐름도의 특성 상자에 붙는 스킬(affects)을 적었다. 흐름도에 없는 스킬은 상자 안 '붙는 스킬' 아이콘으로만 보인다.",
    '- 딜사이클 타임라인의 자리마다 그 자리를 바꾸는 특성(talents, 최대 3개)을 달았다. 같은 스킬이 두 번 나오면 첫 자리에만 달았다.',
    '- 글(설명·조건·근거)은 바꾸지 않았다.',
  ].join('\n'),
  apply(m) {
    const map = MAPS[sid], slots = SLOTS[sid];
    for (const block of m.blocks || []) {
      for (const d of [].concat(block.diagram || [])) {
        for (const l of d.layers) for (const n of l.nodes) {
          if (n.kind === 'talent' && !map[n.skillId]) throw Error(`${sid}: 연결이 없는 특성 ${n.label}`);
          // 사이트 사본만 다른 점: 검사기는 빈 affects 를 받지 않으므로 붙는 스킬이 없는 엉겅퀴 차 두 상자에는 칸을 만들지 않는다.
          if (map[n.skillId]?.length) n.affects = [...map[n.skillId]];
        }
      }
      for (const t of [].concat(block.timeline || [])) for (const r of t.rails) {
        const seen = new Set();
        for (const n of r.nodes) {
          const label = r.label + ' ' + (n.caption || '');
          // '(기만자 기준)'처럼 한 영웅으로 예시한 공통 줄은 두 영웅 장면이 함께 쓰므로 공통 특성만 단다.
          const family = /공통|기준/.test(r.label) ? '' : /운명결속/.test(label) ? 'fate' : /죽음추적자/.test(label) ? 'death' : /기만자/.test(label) ? 'trick' : '';
          const ids = slots[family]?.[n.skillId] || slots.common[n.skillId];
          if (ids && !seen.has(n.skillId)) { n.talents = [...ids]; seen.add(n.skillId); }
        }
      }
    }
    return m;
  },
});
