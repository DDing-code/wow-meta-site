const CAPTIONS = {};

const FAMILY = [[/비늘사령관/, 'scale'], [/불꽃형성자/, 'flame'], [/시간 감시자/, 'chrono']];

module.exports = sid => ({
  source: __filename,
  changelog: [
    '## 2026-11-05 · 특성 ↔ 스킬 연결 도식',
    "- 스킬 구조 흐름도의 특성 상자에 붙는 스킬(affects)을 적었다. 흐름도에 없는 스킬은 상자 안 '붙는 스킬' 아이콘으로만 보인다.",
    '- 딜사이클 타임라인의 자리마다 그 자리를 바꾸는 특성(talents, 최대 3개)을 달았다. 같은 스킬이 두 번 나오면 첫 자리에만 달았다.',
    '- 글(설명·조건·근거)은 바꾸지 않았다.',
  ].join('\n'),
  apply(m) {
    const map = MAPS[sid], slots = SLOTS[sid], captions = CAPTIONS[sid] || {}, rails = RAILS[sid] || {};
    for (const block of m.blocks || []) {
      for (const d of [].concat(block.diagram || [])) {
        for (const l of d.layers) for (const n of l.nodes) {
          if (n.kind === 'talent' && !map[n.skillId]) throw Error(`${sid}: 연결이 없는 특성 ${n.label}`);
          if (map[n.skillId]?.length) n.affects = [...map[n.skillId]];
        }
      }
      for (const t of [].concat(block.timeline || [])) for (const r of t.rails) {
        const seen = new Set();
        for (const n of r.nodes) {
          // 끼워 넣는 줄은 칸 설명 ' · ' 앞부분으로, 칸 설명에 그 구분이 없으면 줄 이름으로 영웅을 가른다.
          // '(… 공통)'·'(… 기준)' 줄은 두 영웅 장면이 함께 쓰므로 공통 특성만 단다(RAILS 에 적은 줄은 그 값).
          const caption = n.caption || '';
          const who = r.kind === 'inserts' && caption.includes(' · ') ? caption.split(' · ')[0] : r.label;
          const family = r.label in rails ? rails[r.label]
            : r.kind !== 'inserts' && /공통|기준/.test(r.label) ? '' : (FAMILY.find(([re]) => re.test(who)) || [, ''])[1];
          const ids = captions[n.caption] || slots[family]?.[n.skillId] || slots.common[n.skillId];
          const key = family + ':' + n.skillId;
          // 끼워 넣는 줄의 칸은 좁아서 이름 두 개가 넘친다 — 앞의 핵심 특성 하나만 단다.
          if (ids && ids.length && !seen.has(key)) { n.talents = r.kind === 'inserts' ? ids.slice(0, 1) : [...ids]; seen.add(key); }
        }
      }
    }
    return m;
  },
});
