module.exports = {
  changelog: [
    '## 2026-11-02 · 특성 ↔ 스킬 연결 도식',
    "- 스킬 구조 흐름도의 특성 상자에 붙는 스킬(affects)을 적었다. 흐름도에 없는 스킬은 상자 안 '붙는 스킬' 아이콘으로만 보인다.",
    '- 단일·오프닝·광역 딜사이클과 레이드·쐐기 탱사이클 타임라인의 자리마다 그 자리를 바꾸는 특성(talents, 최대 3개)을 달았다. 같은 스킬이 두 번 나오면 첫 자리에만 달았다.',
    '- 글(설명·조건·근거)은 바꾸지 않았다.',
  ].join('\n'),
  AFFECTS,
  TALENTS,
  apply(m) {
    const seen = new Set();
    for (const block of m.blocks || []) {
      for (const diagram of [].concat(block.diagram || [])) {
        const map = AFFECTS[diagram.title];
        if (!map) continue;
        seen.add(diagram.title);
        const used = new Set();
        for (const layer of diagram.layers) {
          for (const node of layer.nodes) {
            if (node.kind !== 'talent') continue;
            const targets = map[node.skillId];
            if (!targets) throw new Error(`${diagram.title}: 특성 상자 ${node.label}(${node.skillId})의 affects 가 없음`);
            node.affects = [...targets];
            used.add(String(node.skillId));
          }
        }
        for (const key of Object.keys(map)) if (!used.has(key)) throw new Error(`${diagram.title}: ${key} 는 특성 상자가 아님`);
      }
      for (const timeline of [].concat(block.timeline || [])) {
        const rails = TALENTS[timeline.title];
        if (!rails) continue;
        seen.add(timeline.title);
        for (const rail of timeline.rails) {
          const list = rails[rail.label];
          if (!list) throw new Error(`${timeline.title}: 레일 '${rail.label}' 의 talents 목록이 없음`);
          if (list.length !== rail.nodes.length) throw new Error(`${timeline.title} / ${rail.label}: 자리 수 ${rail.nodes.length} ≠ 목록 ${list.length}`);
          rail.nodes.forEach((node, index) => {
            if (list[index]) node.talents = [...list[index]];
          });
        }
      }
    }
    const expected = [...Object.keys(AFFECTS), ...Object.keys(TALENTS)];
    const missing = expected.filter(title => !seen.has(title));
    if (missing.length) throw new Error('원고에 없는 제목: ' + missing.join(', '));
    return m;
  },
};
