      // 이미 라우트가 있는지 확인
      const routePath = `/guide/${this.className}/${this.specName}`;
      if (appJsContent.includes(routePath)) {
        console.log(`  ⚠️  라우트 이미 존재: ${routePath}`);
        return;
      }

      // TODO: App.js에 라우트 자동 추가 로직
